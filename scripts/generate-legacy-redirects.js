const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.join(__dirname, '..');
const REDIRECT_MAP_PATH = path.join(ROOT_DIR, 'data/legacy-redirects.json');
const COUNTIES_PATH = path.join(ROOT_DIR, 'data/counties.json');
const REDIRECTS_FILE_PATH = path.join(ROOT_DIR, '_redirects');
const GENERATED_MARKER = '<!-- Legacy redirect generated by scripts/generate-legacy-redirects.js -->';

function normalizeRoutePath(routePath) {
    if (!routePath || routePath === '/') return '/';
    const withLeadingSlash = routePath.startsWith('/') ? routePath : `/${routePath}`;
    return withLeadingSlash.endsWith('/') ? withLeadingSlash : `${withLeadingSlash}/`;
}

function toAbsoluteUrl(routePath) {
    return `https://thebeatboutique.ie${normalizeRoutePath(routePath)}`;
}

function buildRedirectPage(targetPath) {
    const absoluteTarget = toAbsoluteUrl(targetPath);

    return `<!DOCTYPE html>
<html lang="en">
<head>
    ${GENERATED_MARKER}
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <meta name="robots" content="noindex, follow">
    <title>Redirecting...</title>
    <link rel="canonical" href="${absoluteTarget}">
    <meta http-equiv="refresh" content="0; url=${absoluteTarget}">
    <script>
        window.location.replace('${absoluteTarget}');
    </script>
</head>
<body>
    <p>Redirecting to <a href="${absoluteTarget}">${absoluteTarget}</a>...</p>
</body>
</html>
`;
}

function readJson(jsonPath) {
    return JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
}

function ensureRedirectDirectory(fromPath) {
    const relative = fromPath.replace(/^\/|\/$/g, '');
    if (!relative) {
        return null;
    }
    return path.join(ROOT_DIR, relative);
}

function loadRedirectEntries() {
    const explicitEntries = readJson(REDIRECT_MAP_PATH);
    const counties = readJson(COUNTIES_PATH);
    const countyEntries = counties.map((county) => ({
        from: `/wedding-band-${county.slug}/`,
        to: `/locations/wedding-band-${county.slug}/`,
    }));

    const merged = [...explicitEntries, ...countyEntries];
    const deduped = new Map();

    merged.forEach((entry) => {
        const from = normalizeRoutePath(entry.from);
        const to = normalizeRoutePath(entry.to);

        if (from === to) {
            return;
        }

        deduped.set(from, { from, to });
    });

    return [...deduped.values()].sort((a, b) => a.from.localeCompare(b.from));
}

function writeRedirectPages(entries) {
    let written = 0;
    let skipped = 0;

    entries.forEach(({ from, to }) => {
        const outputDir = ensureRedirectDirectory(from);
        if (!outputDir) {
            skipped += 1;
            return;
        }

        const outputFile = path.join(outputDir, 'index.html');
        if (fs.existsSync(outputFile)) {
            const existing = fs.readFileSync(outputFile, 'utf8');
            if (!existing.includes(GENERATED_MARKER)) {
                console.warn(`Skipped existing non-generated page: ${from}`);
                skipped += 1;
                return;
            }
        }

        fs.mkdirSync(outputDir, { recursive: true });
        fs.writeFileSync(outputFile, buildRedirectPage(to));
        written += 1;
    });

    return { written, skipped };
}

function writeRedirectRules(entries) {
    const lines = [
        '# Legacy redirect map generated by scripts/generate-legacy-redirects.js',
        '# Used by hosts that support _redirects (e.g. Netlify, Cloudflare Pages).',
        '',
    ];

    entries.forEach(({ from, to }) => {
        const withoutTrailing = from.endsWith('/') ? from.slice(0, -1) : from;
        if (withoutTrailing) {
            lines.push(`${withoutTrailing} ${to} 301`);
        }
        lines.push(`${from} ${to} 301`);
    });

    lines.push('');
    fs.writeFileSync(REDIRECTS_FILE_PATH, lines.join('\n'));
}

function main() {
    const entries = loadRedirectEntries();
    const { written, skipped } = writeRedirectPages(entries);
    writeRedirectRules(entries);

    console.log(`Generated legacy redirect pages: ${written}`);
    console.log(`Skipped legacy redirect pages: ${skipped}`);
    console.log(`Total redirect rules written: ${entries.length}`);
    console.log('Wrote _redirects map for 301-capable hosting platforms.');
}

main();
