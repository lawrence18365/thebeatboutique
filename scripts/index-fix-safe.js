#!/usr/bin/env node
/**
 * Phase 3 — Safe auto-fixes (low-risk, reversible, additive only).
 *
 * 1. Adds missing 301 redirects for legacy 404s into data/legacy-redirects.json
 *    (the source of truth). Never overwrites or changes an existing rule.
 *    Then re-runs the existing generators to rebuild _redirects + sitemaps.
 * 2. Regenerates sitemaps via the existing generator (which already emits only
 *    canonical, indexable, non-noindex, 200 URLs that exist on disk).
 * 3. Produces a noindex audit (data/audit/index-noindex-audit.md) — REPORT ONLY,
 *    classifying each noindex'd file as keep / should-redirect / review.
 *
 * Does NOT delete any files. Backs up legacy-redirects.json before editing and
 * prints a git diff --stat so every change is reviewable/revertible.
 *
 * Flags:
 *   --dry-run   Show what would change; write nothing.
 *
 * Usage: node scripts/index-fix-safe.js [--dry-run]
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT_DIR = path.join(__dirname, '..');
const AUDIT_DIR = path.join(ROOT_DIR, 'data', 'audit');
const PLAN_JSON = path.join(AUDIT_DIR, 'index-fix-plan.json');
const REDIRECTS_JSON = path.join(ROOT_DIR, 'data', 'legacy-redirects.json');
const COUNTIES_JSON = path.join(ROOT_DIR, 'data', 'counties.json');
const NOINDEX_AUDIT = path.join(AUDIT_DIR, 'index-noindex-audit.md');

const DRY_RUN = process.argv.includes('--dry-run');

const INTENTIONAL_NOINDEX_SLUGS = ['thank-you', 'showcase-confirmed', '404', 'guestlist'];

function normPath(p) {
    if (!p || p === '/') return '/';
    const lead = p.startsWith('/') ? p : `/${p}`;
    return lead.endsWith('/') ? lead : `${lead}/`;
}

function run(cmd) {
    console.log(`  $ ${cmd}`);
    if (DRY_RUN) return;
    execSync(cmd, { cwd: ROOT_DIR, stdio: 'inherit' });
}

// ── 1. Merge new redirects ──────────────────────────────────────────────────
function mergeRedirects() {
    if (!fs.existsSync(PLAN_JSON)) {
        console.warn('No index-fix-plan.json — run npm run index:plan first. Skipping redirect merge.');
        return { added: [], skipped: [] };
    }
    const plan = JSON.parse(fs.readFileSync(PLAN_JSON, 'utf8'));
    const proposed = (plan.autoRedirects || []).map(r => ({ from: normPath(r.from), to: normPath(r.to) }));

    const existing = JSON.parse(fs.readFileSync(REDIRECTS_JSON, 'utf8'));
    const existingFroms = new Set(existing.map(e => normPath(e.from)));

    // County auto-rules are generated separately; don't duplicate them here.
    const counties = JSON.parse(fs.readFileSync(COUNTIES_JSON, 'utf8'));
    const countyFroms = new Set(counties.map(c => normPath(`/wedding-band-${c.slug}/`)));

    const added = [], skipped = [];
    for (const r of proposed) {
        if (r.from === r.to) { skipped.push({ ...r, reason: 'from===to' }); continue; }
        if (existingFroms.has(r.from)) { skipped.push({ ...r, reason: 'already exists' }); continue; }
        if (countyFroms.has(r.from)) { skipped.push({ ...r, reason: 'covered by county auto-rule' }); continue; }
        added.push(r);
        existing.push(r);
        existingFroms.add(r.from);
    }

    console.log(`\n[1/3] Legacy redirects: +${added.length} new, ${skipped.length} skipped`);
    added.forEach(r => console.log(`   + ${r.from} → ${r.to}`));
    skipped.forEach(r => console.log(`   · skip ${r.from} (${r.reason})`));

    if (added.length && !DRY_RUN) {
        fs.copyFileSync(REDIRECTS_JSON, REDIRECTS_JSON + '.bak');
        fs.writeFileSync(REDIRECTS_JSON, JSON.stringify(existing, null, 4) + '\n');
        console.log(`   backup → ${path.relative(ROOT_DIR, REDIRECTS_JSON)}.bak`);
    }
    return { added, skipped };
}

// ── 2. Regenerate _redirects + sitemaps via existing generators ─────────────
function regenerate(redirectsChanged) {
    console.log('\n[2/3] Regenerating _redirects + sitemaps (existing generators):');
    if (redirectsChanged) run('node scripts/generate-legacy-redirects.js');
    else console.log('  (no new redirects — skipping _redirects rebuild)');
    run('node scripts/generate-sitemaps.js');
}

// ── 3. Noindex audit (report only) ──────────────────────────────────────────
function walkHtml(dir, acc = []) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        if (e.name === 'node_modules' || e.name.startsWith('.') || e.name === 'tmp' || e.name === 'output') continue;
        const full = path.join(dir, e.name);
        if (e.isDirectory()) walkHtml(full, acc);
        else if (e.name.endsWith('.html')) acc.push(full);
    }
    return acc;
}

function hasNoindex(content) {
    return /name=["']robots["']\s+content=["'][^"']*noindex/i.test(content);
}
function isGeneratedRedirectStub(content) {
    return content.includes('Legacy redirect generated by') || /http-equiv=["']refresh["']/i.test(content);
}
function suggestRedirectTarget(routePath) {
    const p = routePath.replace(/\/+$/, '');
    const rules = [
        [/^\/(book|book-us|contact|contact-us|video|videos|showreel)$/, '/showcase/'],
        [/^\/(playlist|songlist|songs)$/, '/song-list/'],
        [/^\/(prices|pricing|wedding-band-prices)$/, '/pricing-guide/'],
        [/^\/(our-fans|testimonials)$/, '/reviews/'],
        [/^\/why-us$/, '/about/'],
        [/^\/wedding-band-([a-z-]+)$/, (m) => `/locations/wedding-band-${m[1]}/`],
    ];
    for (const [re, t] of rules) { const m = p.match(re); if (m) return typeof t === 'function' ? t(m) : t; }
    return null;
}

function noindexAudit() {
    const files = walkHtml(ROOT_DIR);
    const rows = [];
    for (const file of files) {
        const content = fs.readFileSync(file, 'utf8');
        if (!hasNoindex(content)) continue;
        const rel = path.relative(ROOT_DIR, file);
        const routePath = '/' + rel.replace(/index\.html$/, '').replace(/\.html$/, '').replace(/\/$/, '') + '/';
        const route = routePath.replace(/\/+/g, '/');

        let recommendation, detail;
        if (isGeneratedRedirectStub(content)) {
            recommendation = 'KEEP'; detail = 'Generated redirect stub (noindex,follow) — correct.';
        } else if (INTENTIONAL_NOINDEX_SLUGS.some(s => route === `/${s}/` || route.includes(`/${s}/`))) {
            recommendation = 'KEEP'; detail = 'Utility/conversion/legacy page — intentional exclusion.';
        } else {
            const target = suggestRedirectTarget(route);
            if (target) {
                recommendation = 'REDIRECT'; detail = `Legacy duplicate. Prefer 301 → ${target}: delete this duplicate HTML so _redirects fires (manual confirm — make a git commit first).`;
            } else {
                recommendation = 'REVIEW'; detail = 'Noindex with no redirect target — confirm this page should be excluded; if not, remove the noindex meta.';
            }
        }
        rows.push({ rel, route, recommendation, detail });
    }

    rows.sort((a, b) => a.recommendation.localeCompare(b.recommendation) || a.rel.localeCompare(b.rel));
    const counts = rows.reduce((m, r) => (m[r.recommendation] = (m[r.recommendation] || 0) + 1, m), {});

    const L = [];
    L.push('# Noindex Audit — thebeatboutique.ie');
    L.push('');
    L.push(`_Generated ${new Date().toISOString()} · ${rows.length} files contain a noindex meta tag._`);
    L.push('');
    L.push(`KEEP: ${counts.KEEP || 0} · REDIRECT: ${counts.REDIRECT || 0} · REVIEW: ${counts.REVIEW || 0}`);
    L.push('');
    L.push('> No files are deleted by this script. REDIRECT/REVIEW items require a manual, committed change.');
    L.push('');
    L.push('| File | Route | Recommendation | Detail |');
    L.push('|---|---|---|---|');
    for (const r of rows) L.push(`| \`${r.rel}\` | \`${r.route}\` | **${r.recommendation}** | ${r.detail} |`);
    L.push('');

    console.log(`\n[3/3] Noindex audit: ${rows.length} files (KEEP ${counts.KEEP || 0}, REDIRECT ${counts.REDIRECT || 0}, REVIEW ${counts.REVIEW || 0})`);
    if (!DRY_RUN) {
        fs.writeFileSync(NOINDEX_AUDIT, L.join('\n'));
        console.log(`   ✓ ${path.relative(ROOT_DIR, NOINDEX_AUDIT)}`);
    }
    return counts;
}

function main() {
    console.log(DRY_RUN ? '=== Phase 3 safe fixes (DRY RUN) ===' : '=== Phase 3 safe fixes ===');
    const { added } = mergeRedirects();
    regenerate(added.length > 0);
    noindexAudit();

    if (!DRY_RUN) {
        console.log('\n— git diff --stat —');
        try { execSync('git diff --stat', { cwd: ROOT_DIR, stdio: 'inherit' }); } catch (e) {}
    }
    console.log('\n✓ Phase 3 done. Review the diff, then commit + deploy.');
}

main();
